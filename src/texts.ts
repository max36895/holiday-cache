import { Text } from 'umbot/utils';
import { IParticipant } from './core/types';

const PLATFORM_LABELS: Readonly<Record<string, string>> = {
    telegram: 'Telegram',
    vk: 'VK',
    max_app: 'MAX',
    alisa: 'Алиса',
};

/**
 * Название мессенджера для людей.
 *
 * @param platform Имя платформы umbot
 * @returns «Telegram», «VK», «MAX», «Алиса» или имя как есть
 */
export function platformLabel(platform: string): string {
    return PLATFORM_LABELS[platform] ?? platform;
}

/**
 * Имя участника со значком мессенджера: «Аня (VK)».
 *
 * @param participant Участник
 * @returns Подпись участника
 */
export function participantLabel(participant: IParticipant): string {
    // Имя стёрто у выбывших после фиксации состава (исключение, «удалить мои данные»):
    // причина выбытия не раскрывается, поэтому подпись нейтральная
    const name = participant.userId ? participant.name : 'участник выбыл';
    return `${name} (${platformLabel(participant.platform)})`;
}

/**
 * Имя в приличном виде: «пётр» становится «Пётр», каждое слово — с заглавной.
 * Остальные буквы не трогаем: «Анна-Мария» и «McDonald» остаются как ввели.
 *
 * @param name Имя, введённое пользователем
 * @returns Имя с заглавными первыми буквами
 */
export function titleCaseName(name: string): string {
    return name
        .split(/\s+/)
        .filter(Boolean)
        .map((word) => word[0]!.toUpperCase() + word.slice(1))
        .join(' ');
}

/**
 * «7 участников»: число с нужной формой слова.
 *
 * @param count Число участников
 * @returns Число и слово
 */
export function membersCount(count: number): string {
    return `${count} ${Text.getEnding(count, ['участник', 'участника', 'участников'])}`;
}

